"""Downloadable JSON reports (per module and consolidated)."""
from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any, Dict, Optional

DEMO_NOTICE = "Demonstration result \u2014 not generated by live AI."
GENERAL_DISCLAIMER = ("AI-assisted and conceptual output for education and preliminary screening only. It does not "
                      "replace inspection or certification by qualified safety, structural or valuation professionals.")


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def build_module_report(kind: str, entry: Dict[str, Any], disclaimer: str = GENERAL_DISCLAIMER) -> Dict[str, Any]:
    """Wrap a stored result entry {data, mode, source_name, timestamp} for download."""
    mode = entry.get("mode", "demo")
    return {
        "report_type": kind,
        "generated_at": entry.get("timestamp") or _now(),
        "result_source": {"live": "Gemini live AI", "demo": "demonstration data", "calculation": "rule-based calculation"}.get(mode, mode),
        "demonstration_notice": DEMO_NOTICE if mode == "demo" else None,
        "source_file": entry.get("source_name"),
        "disclaimer": disclaimer,
        "result": entry.get("data"),
    }


def build_consolidated_report(results: Dict[str, Optional[Dict[str, Any]]], weather: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    from modules import crack_analysis, safety_analysis, valuation

    sections: Dict[str, Any] = {}
    for key, kind, disc in (("safety", "ppe_safety_audit", safety_analysis.DISCLAIMER),
                            ("crack", "crack_diagnostics", crack_analysis.DISCLAIMER),
                            ("valuation", "planning_valuation", valuation.DISCLAIMER)):
        entry = results.get(key)
        sections[kind] = build_module_report(kind, entry, disc) if entry else None
    return {
        "report_type": "consolidated_project_report",
        "project": "Multimodal Construction Intelligence Platform",
        "generated_at": _now(),
        "modules_completed": [k for k, v in sections.items() if v],
        "demonstration_notice": DEMO_NOTICE if any(v and v["demonstration_notice"] for v in sections.values()) else None,
        "sections": sections,
        "weather_advisory": weather,
        "disclaimer": GENERAL_DISCLAIMER,
    }


def to_json_bytes(payload: Dict[str, Any]) -> bytes:
    return json.dumps(payload, indent=2, ensure_ascii=False, default=str).encode("utf-8")
